import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import sharp from 'sharp';
import { createApp } from '../src/app.mjs';
import { createUser } from '../src/security.mjs';
import { openDatabase } from '../src/database.mjs';

test('staff image workflow protects drafts and administrative operations', async t => {
  const dataDir=await mkdtemp(join(tmpdir(),'vuga-media-test-'));
  const {app,db}=createApp({dataDir,origin:'http://site.test',secureCookies:false});
  createUser(db,'admin','admin-password-123','admin');
  const server=app.listen(0,'127.0.0.1');
  await new Promise(resolve=>server.once('listening',resolve));
  const url=`http://127.0.0.1:${server.address().port}/api/media`;
  t.after(async()=>{server.closeAllConnections(); await new Promise(resolve=>server.close(resolve)); db.close(); await rm(dataDir,{recursive:true,force:true});});
  const send=(path,options={})=>fetch(url+path,options);
  const origin={Origin:'http://site.test'};
  const json=(method,body,auth={})=>({method,headers:{...origin,'Content-Type':'application/json',...auth},body:JSON.stringify(body)});
  assert.equal((await send('/manage/galleries')).status,401);
  assert.equal((await send('/login',json('POST',{username:'admin',password:'wrong'},{}))).status,401);
  assert.equal((await send('/login',{method:'POST',headers:{'Content-Type':'application/json'},body:'{}'})).status,403);
  let response=await send('/login',json('POST',{username:'admin',password:'admin-password-123'}));
  assert.equal(response.status,200);
  const adminCookie=response.headers.get('set-cookie').split(';')[0];
  const admin=(await response.json());
  const adminAuth={Cookie:adminCookie,'X-CSRF-Token':admin.csrf};
  assert.equal((await send('/manage/users',json('POST',{username:'editor',password:'editor-password-123',role:'staff'},{Cookie:adminCookie}))).status,403);
  assert.equal((await send('/manage/users',json('POST',{username:'editor',password:'editor-password-123',role:'staff'},adminAuth))).status,201);
  response=await send('/login',json('POST',{username:'editor',password:'editor-password-123'}));
  const staffCookie=response.headers.get('set-cookie').split(';')[0];
  const staff=(await response.json());
  const staffAuth={Cookie:staffCookie,'X-CSRF-Token':staff.csrf};
  assert.equal((await send('/manage/users',{headers:staffAuth})).status,403);
  const gallery='cyanika-technical-secondary-school-outreach';
  const upload=async (bytes,type='image/png')=>{const form=new FormData();form.set('title','Test photo');form.set('alt','A test image');form.set('image',new Blob([bytes],{type}),'photo.png');return send(`/manage/galleries/${gallery}/photos`,{method:'POST',headers:{...origin,...staffAuth},body:form});};
  assert.equal((await upload(Buffer.from('not an image'))).status,400);
  const image=await sharp({create:{width:80,height:50,channels:3,background:'#439a66'}}).png().toBuffer();
  response=await upload(image); assert.equal(response.status,201);
  const {id}=await response.json();
  assert.equal((await send(`/images/${id}/thumb`)).status,404);
  assert.equal((await send(`/manage/images/${id}/thumb`,{headers:staffAuth})).status,200);
  assert.equal((await send(`/galleries/${gallery}`).then(r=>r.json())).photos.length,0);
  assert.equal((await send(`/manage/photos/${id}`,json('PATCH',{title:'Test photo',alt:'A test image',caption:'Outreach moment',published:true},staffAuth))).status,200);
  response=await send(`/images/${id}/thumb`); assert.equal(response.status,200); assert.match(response.headers.get('content-type'),/image\/webp/);
  const published=(await send(`/galleries/${gallery}`).then(r=>r.json())).photos;
  assert.equal(published.length,1);
  assert.equal(published[0].caption,'Outreach moment');
  assert.equal((await send(`/manage/galleries/${gallery}/order`,json('PUT',{ids:[]},staffAuth))).status,400);
  assert.equal((await send(`/manage/photos/${id}`,json('PATCH',{title:'Test photo',alt:'A test image',published:false},staffAuth))).status,200);
  assert.equal((await send(`/images/${id}/thumb`)).status,404);
  assert.equal((await upload(Buffer.alloc(15*1024*1024+1))).status,400);
  assert.equal((await send(`/manage/users/${staff.user.id}`,json('PATCH',{disabled:true},adminAuth))).status,200);
  assert.equal((await send('/session',{headers:{Cookie:staffCookie}})).status,401);
  for (let i=0;i<8;i++) assert.equal((await send('/login',json('POST',{username:'unknown',password:'wrong'}))).status,401);
  assert.equal((await send('/login',json('POST',{username:'unknown',password:'wrong'}))).status,429);
});

test('database records persist when the service reopens them', async t => {
  const root=await mkdtemp(join(tmpdir(),'vuga-media-restart-'));
  t.after(()=>rm(root,{recursive:true,force:true}));
  let db=openDatabase(root);
  createUser(db,'persisted','long-enough-password','staff');
  db.close();
  db=openDatabase(root);
  assert.equal(db.prepare('SELECT role FROM users WHERE username=?').get('persisted').role,'staff');
  assert.equal(db.prepare('SELECT COUNT(*) AS n FROM galleries').get().n,2);
  db.close();
});
